    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id     BIGINT NOT NULL,
    slip_item_id  BIGINT,
    type          VARCHAR(30) NOT NULL,
    amount        NUMERIC(12, 0) NOT NULL,
    paid_amount   NUMERIC(12, 0) NOT NULL DEFAULT 0,
    status        VARCHAR(20) NOT NULL,
    overdue_days  INT,
    reason        TEXT,
    waived_by     BIGINT,
    waived_reason TEXT,
    created_by    BIGINT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at    TIMESTAMPTZ,
    updated_by    BIGINT,
    CONSTRAINT fk_fines_reader FOREIGN KEY (reader_id) REFERENCES readers (id),
    CONSTRAINT fk_fines_slip_item FOREIGN KEY (slip_item_id) REFERENCES borrow_slip_items (id),
    CONSTRAINT fk_fines_waived_by FOREIGN KEY (waived_by) REFERENCES users (id),
    CONSTRAINT fk_fines_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT ck_fines_type CHECK (type IN (
        'OVERDUE', 'DAMAGED_MINOR', 'DAMAGED_MAJOR', 'LOST', 'CARD_REISSUE', 'OTHER'
