    approved_at      TIMESTAMPTZ,
    approved_by      BIGINT,
    rejected_reason  TEXT,
    pickup_deadline  TIMESTAMPTZ,
    borrowed_at      TIMESTAMPTZ,
    issued_by        BIGINT,
    deposit_amount   NUMERIC(12, 0) NOT NULL DEFAULT 0,
    note             TEXT,
    cancelled_at     TIMESTAMPTZ,
    cancelled_by     BIGINT,
    cancel_reason    TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at       TIMESTAMPTZ,
    created_by       BIGINT,
    updated_by       BIGINT,
    CONSTRAINT uq_borrow_slips_slip_code UNIQUE (slip_code),
    CONSTRAINT fk_borrow_slips_reader FOREIGN KEY (reader_id) REFERENCES readers (id),
    CONSTRAINT fk_borrow_slips_approved_by FOREIGN KEY (approved_by) REFERENCES users (id),
    CONSTRAINT fk_borrow_slips_issued_by FOREIGN KEY (issued_by) REFERENCES users (id),
    CONSTRAINT fk_borrow_slips_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES users (id),
