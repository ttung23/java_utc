    CONSTRAINT ck_fines_status CHECK (status IN ('UNPAID', 'PARTIAL', 'PAID', 'WAIVED', 'REDUCED')),
    CONSTRAINT ck_fines_paid_amount CHECK (paid_amount <= amount)
);

